#!/usr/bin/env node
/**
 * gen-codebase-map.mjs — CODEBASE-MAP.md, generated from disk and the ledger.
 *
 * POSTURE: BLOCKS with --check. Run by `.github/workflows/ci.yml`.
 *
 * WHY ONLY THIS ONE OF THE FOUR MEMORY FILES (Phase 6, 2026-08-12)
 *
 * The Phase 6 gate said all four memory files become generated views over the ledger, with
 * the migration proven non-lossy. Two measurements changed that, and the amendment is
 * recorded in DECISIONS.md rather than applied quietly:
 *
 *   1. THREE OF THE FOUR ARE EMPTY TEMPLATES. CODEBASE-MAP.md (20 lines) and
 *      USER-INSIGHTS.md (18) literally say "Empty."; LONG-TERM.md holds ~10 real lines.
 *      The "data migration over files holding real founder memory" was one file.
 *
 *   2. THAT ONE FILE CANNOT BE A LEDGER VIEW. DECISIONS.md holds 25 entries shaped
 *      Context / Options considered / Decision / Rationale / Reversibility. A claim is
 *      `assert + evidence + expiry`. The ledger has no field for a REJECTED option or for
 *      rationale, so "non-lossy" fails by construction — not by implementation difficulty.
 *      Collapsing it would destroy the only part of a decision record still worth reading a
 *      year later. It stays human and append-only.
 *
 * So CODEBASE-MAP.md is generated, and the non-lossy proof is real rather than argued: the
 * pre-migration file was an empty template, so nothing was lost, and that is checkable.
 * LONG-TERM.md and USER-INSIGHTS.md are recorded as not-ledger-derivable, with the reason.
 *
 * WHAT IT MAPS. Not "every file" — a listing is not a map. It answers the question a new
 * agent actually has: what can stop me, and where does the enforcement live.
 *
 * Usage: node scripts/gen-codebase-map.mjs [--check]
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const TARGET = path.join(ROOT, '.claude', 'memory', 'CODEBASE-MAP.md');
const abs = (p) => path.join(ROOT, p);
const exists = (p) => fs.existsSync(abs(p));
const read = (p) => fs.readFileSync(abs(p), 'utf8');

// A file's POSTURE header is the repo's own convention for "can this stop anything".
// Reading it here rather than restating it keeps one source of truth: if a hook changes
// from ADVISES to BLOCKS, this map changes with it and nobody has to remember.
function posture(rel) {
  try {
    const head = read(rel).split('\n').slice(0, 6).join('\n');
    const m = /POSTURE:\s*([A-Z]+)/.exec(head);
    return m ? m[1] : '—';
  } catch {
    return '—';
  }
}

function listDir(rel, filter = () => true) {
  try {
    return fs.readdirSync(abs(rel)).filter(filter).sort();
  } catch {
    return [];
  }
}

function npmScripts() {
  try {
    return JSON.parse(read('package.json')).scripts || {};
  } catch {
    return {};
  }
}

function ledgerClaims() {
  try {
    return JSON.parse(read('.claude/ledger/index.json')).claims || [];
  } catch {
    return [];
  }
}

function build() {
  const scripts = npmScripts();
  const claims = ledgerClaims();
  const L = [];
  const w = (s = '') => L.push(s);

  w('# Codebase Map');
  w('');
  w('**Generated by `node scripts/gen-codebase-map.mjs` — do not edit.** CI fails if this file drifts');
  w('from disk (`npm run check:map`), which is the only thing that makes a map trustworthy: a hand-maintained');
  w('map is accurate exactly until the first person forgets, and then it is worse than none.');
  w('');
  w('This does not list every file. A listing is not a map. It answers the question a new agent actually');
  w('has — **what can stop me, and where does that live** — because in this repo the enforcement *is* the');
  w('architecture.');
  w('');

  w('## What can block');
  w('');
  w('Every file below declares its own `POSTURE:` header; this table reads that header rather than restating');
  w('it, so a hook that changes posture changes this map with it.');
  w('');
  w('| File | Posture | Runs on |');
  w('|---|---|---|');
  let settings = { hooks: {} };
  try { settings = JSON.parse(read('.claude/settings.json')); } catch { /* reported below */ }
  const eventOf = {};
  for (const [event, blocks] of Object.entries(settings.hooks || {})) {
    for (const b of blocks) for (const h of b.hooks || []) {
      const m = /(\.claude\/hooks\/[\w.-]+)/.exec(h.command || '');
      if (m) eventOf[m[1]] = (eventOf[m[1]] ? `${eventOf[m[1]]}, ` : '') + event;
    }
  }
  // statusLine is registered outside `hooks`, so reading only `hooks` reported the
  // statusline script as unregistered — a map that is confidently wrong about whether
  // something runs is the exact failure this file is supposed to end.
  {
    const m = /(\.claude\/hooks\/[\w.-]+)/.exec((settings.statusLine && settings.statusLine.command) || '');
    if (m) eventOf[m[1]] = (eventOf[m[1]] ? `${eventOf[m[1]]}, ` : '') + 'statusLine';
  }
  for (const f of listDir('.claude/hooks')) {
    const rel = `.claude/hooks/${f}`;
    w(`| \`${rel}\` | ${posture(rel)} | ${eventOf[rel] || 'not registered'} |`);
  }
  for (const f of listDir('.github/workflows', (x) => x.endsWith('.yml'))) {
    const rel = `.github/workflows/${f}`;
    const text = read(rel);
    const on = /schedule:/.test(text) ? 'schedule' : /pull_request/.test(text) ? 'pull_request' : 'manual';
    w(`| \`${rel}\` | ${posture(rel)} | ${on} |`);
  }
  w('');

  w('## Verification commands');
  w('');
  w('`npm run check` is the gate; everything below is a component of it or a read-only query.');
  w('');
  w('| Script | Command |');
  w('|---|---|');
  for (const k of Object.keys(scripts).sort()) {
    w(`| \`npm run ${k}\` | \`${scripts[k].replace(/\|/g, '\\|').slice(0, 110)}\` |`);
  }
  w('');

  w('## Core modules');
  w('');
  w('| File | Purpose |');
  w('|---|---|');
  const PURPOSE = {
    'scripts/lib/claims.js': 'The ONE YAML parser and the closed claim schema. Do not add a second',
    'scripts/lib/classifier.js': 'The ONE risk implementation. Two would disagree during the incident',
    'scripts/lib/resolvers.js': 'Four resolvers. `unresolved` is never `pass` — the invariant the ledger rests on',
    'scripts/lib/usage.js': 'Spend measurement from session transcripts; append-only is what makes it fast',
    'scripts/ledger.mjs': 'build · rebuild · lint · verify · judge · events · views · sweep',
    'scripts/check-registration.mjs': 'The fabrication catcher: dead paths, drifted counts, phantom agents, NUL bytes',
    'scripts/gen-codebase-map.mjs': 'This file',
  };
  for (const [f, p] of Object.entries(PURPOSE)) {
    if (exists(f)) w(`| \`${f}\` | ${p} |`);
  }
  w('');

  w('## Tests');
  w('');
  w('| File | Subject |');
  w('|---|---|');
  for (const f of listDir('scripts', (x) => x.endsWith('.test.mjs'))) {
    let subject = '—';
    try {
      const m = /^\/\/ (?:POSTURE[^\n]*\n\/\/\n)?\/\/ ([^\n]+)/m.exec(read(`scripts/${f}`));
      const line = read(`scripts/${f}`).split('\n').find((l) => l.startsWith('// scripts/'));
      subject = line ? line.replace(/^\/\/ /, '').split('—').slice(1).join('—').trim() || '—' : (m ? m[1] : '—');
    } catch { /* keep the dash */ }
    w(`| \`scripts/${f}\` | ${subject} |`);
  }
  w('');

  w('## What the system asserts');
  w('');
  w(`${claims.length} project claims in \`.claude/ledger/index.json\`, plus any \`scope: global\` claims in`);
  w('`~/.warroom/ledger/global.yml` — machine state a fresh clone does not have, which the ledger reports');
  w('rather than skipping silently.');
  w('');
  const byKind = {};
  for (const c of claims) byKind[c.kind] = (byKind[c.kind] || 0) + 1;
  w('| Kind | Count |');
  w('|---|---|');
  for (const k of Object.keys(byKind).sort()) w(`| ${k} | ${byKind[k]} |`);
  w('');
  w('Browse them with `npm run ledger:views`; sweep for expiry with `npm run ledger:sweep`.');
  w('');

  w('## The other three memory files');
  w('');
  w('| File | Generated? | Why |');
  w('|---|---|---|');
  w('| `DECISIONS.md` | **No — human, append-only** | It holds rejected options and rationale. The ledger stores `assert + evidence + expiry` and has no field for either, so a generated view would drop the only part still worth reading a year later. "Non-lossy" fails by construction, not by difficulty |');
  w('| `LONG-TERM.md` | **No — not ledger-derivable** | Founder preferences and recurring patterns. Not claims: they carry no evidence and expire on nothing |');
  w('| `USER-INSIGHTS.md` | **No — not ledger-derivable** | Customer language and JTBD, sourced from research. Empty today, and CMO is hard-gated on it |');
  w('');
  w('*Phase 6 amended the gate criterion that asked for all four. The measurement that forced it is in');
  w('`DECISIONS.md` — three of the four were empty templates, and the fourth could not be one.*');
  w('');

  return L.join('\n') + '\n';
}

const generated = build();
const checkOnly = process.argv.includes('--check');

if (checkOnly) {
  let current = '';
  try { current = fs.readFileSync(TARGET, 'utf8'); } catch { /* missing counts as drift */ }
  if (current !== generated) {
    process.stderr.write(
      '✗ CODEBASE-MAP.md is stale. It is generated, not written — run `npm run build:map`.\n' +
        '  A map that drifts from disk is worse than no map: it is trusted and wrong.\n'
    );
    process.exit(1);
  }
  process.stdout.write('✓ CODEBASE-MAP.md matches disk.\n');
  process.exit(0);
}

fs.writeFileSync(TARGET, generated);
process.stdout.write(`✓ wrote ${path.relative(ROOT, TARGET)} — ${generated.split('\n').length} lines.\n`);
